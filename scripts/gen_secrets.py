#!/usr/bin/env python3
"""Generate random AttackSentry credentials and write them to .env files.

Writes:
  * deploy/docker-compose/.env  (for docker compose)
  * Sentry/.env                 (for `python -m sentry` dev run)

Generates cryptographically-random values for every secret so no default
credentials are ever used.
"""
from __future__ import annotations

import secrets
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


def random_secret(nbytes: int = 32) -> str:
    return secrets.token_hex(nbytes)


def random_password() -> str:
    return secrets.token_urlsafe(18)


def main() -> None:
    secret_key = random_secret(32)
    admin_password = random_password()
    db_password = random_password()
    nats_password = random_password()

    compose_env = REPO / "deploy" / "docker-compose" / ".env"
    sentry_env = REPO / "Sentry" / ".env"

    compose_env.write_text(
        f"""# Auto-generated by scripts/gen_secrets.py — do not commit.
SENTRY_SECRET_KEY={secret_key}
SENTRY_BOOTSTRAP_ADMIN_PASSWORD={admin_password}
POSTGRES_PASSWORD={db_password}
POSTGRES_USER=attacksentry
POSTGRES_DB=attacksentry
NATS_USER=attacksentry
NATS_PASSWORD={nats_password}
NATS_BIND_HOST=127.0.0.1
SENTRY_COOKIE_SECURE=false
SENTRY_LLM_PROVIDER=none
SENTRY_LLM_BASE_URL=http://host.docker.internal:1234
SENTRY_LLM_MODEL=default
SENTRY_BASELINE_HOURS=72
SENTRY_RETENTION_DAYS=30
FRONTEND_PORT=8080
"""
    )

    sentry_env.write_text(
        f"""# Auto-generated by scripts/gen_secrets.py — do not commit.
SENTRY_ENVIRONMENT=development
SENTRY_DEBUG=true
SENTRY_SECRET_KEY={secret_key}
SENTRY_BOOTSTRAP_ADMIN_PASSWORD={admin_password}
SENTRY_BOOTSTRAP_ADMIN_USERNAME=admin
SENTRY_BOOTSTRAP_ADMIN_EMAIL=admin@localhost
SENTRY_DATABASE_URL=sqlite+aiosqlite:///{REPO / 'Sentry' / 'attacksentry.db'}
SENTRY_COOKIE_SECURE=false
SENTRY_LLM_PROVIDER=none
SENTRY_LLM_BASE_URL=http://127.0.0.1:1234
SENTRY_LLM_MODEL=default
SENTRY_BASELINE_HOURS=72
"""
    )

    print(f"Wrote {compose_env}")
    print(f"Wrote {sentry_env}")
    print("admin username : admin")
    print(f"admin password : {admin_password}")
    print("AI triage      : disabled (enable after configuring a provider)")


if __name__ == "__main__":
    main()
